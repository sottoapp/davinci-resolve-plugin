#!/usr/bin/env python3
"""Regenerate docs/skill-library.md from skills/*/SKILL.md. Fails if a skill is not in a group."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "plugin"
NEW = {  # authored in this repo; everything else is ported from upstream
    "resolve-api-reliability", "resolve-color-management", "resolve-subtitles", "resolve-proxy-relink",
    "resolve-transcript-assembly", "resolve-delivery-specs", "resolve-qc-gate", "authoring-resolve-skills",
    "resolve-guide-project-media", "resolve-guide-cut-edit", "resolve-guide-color", "resolve-guide-fusion",
    "resolve-guide-fairlight", "resolve-guide-deliver", "editing-principles", "editing-interview-documentary",
    "editing-sound-music", "editing-short-form-vertical", "editing-review-feedback",
    "resolve-nle-roundtrip", "resolve-edition-features", "resolve-session-handoff",
    "realestate-video-editing", "realestate-color-in-resolve", "realestate-delivery-compliance",
    "wedding-video-editing", "wedding-color-audio-in-resolve", "wedding-delivery-client-care",
    "event-video-editing", "event-color-audio-in-resolve", "event-delivery-compliance",
    "resolve-titles-and-lower-thirds", "wedding-effects-transitions-titles", "event-graphics-titles-transitions",
    "resolve-speed-ramps-transitions", "resolve-templates-and-batching",
}
GROUPS = [
    ("Learn Resolve itself (application guides)", ["resolve-guide-project-media", "resolve-guide-cut-edit",
        "resolve-guide-color", "resolve-guide-fusion", "resolve-guide-fairlight", "resolve-guide-deliver",
        "resolve-edition-features", "resolve-speed-ramps-transitions", "resolve-templates-and-batching", "resolve-titles-and-lower-thirds"]),
    ("Vertical: real estate (how to edit a specific kind of video)", ["realestate-video-editing", "realestate-color-in-resolve", "realestate-delivery-compliance"]),
    ("Vertical: weddings", ["wedding-video-editing", "wedding-color-audio-in-resolve", "wedding-effects-transitions-titles", "wedding-delivery-client-care"]),
    ("Vertical: events (conferences, corporate, festivals, galas, sports)", ["event-video-editing", "event-color-audio-in-resolve", "event-graphics-titles-transitions", "event-delivery-compliance"]),
    ("Editing craft (principles → Resolve actions)", ["editing-principles", "editing-interview-documentary",
        "editing-sound-music", "editing-short-form-vertical", "editing-review-feedback"]),
    ("Drive Resolve through MCP — orientation & safety", ["resolve-mcp", "resolve-session", "resolve-session-handoff", "resolve-api-reliability"]),
    ("MCP — ingest & prep", ["resolve-media-pool", "resolve-media-analysis", "resolve-proxy-relink"]),
    ("MCP — edit", ["resolve-edit", "resolve-rough-cut", "resolve-tighten-recording", "resolve-transcript-assembly", "house-style"]),
    ("MCP — conform", ["resolve-conform", "resolve-nle-roundtrip"]),
    ("MCP — color", ["resolve-color-management", "resolve-color"]),
    ("MCP — audio, captions & Fusion", ["resolve-audio", "resolve-subtitles", "resolve-fusion"]),
    ("MCP — deliver & QC", ["resolve-delivery-specs", "resolve-delivery", "resolve-qc-gate"]),
    ("Meta", ["authoring-resolve-skills"]),
]
out = ["# Skill library\n",
       "Generated by `scripts/gen_skill_library.py` (repo root) from `skills/*/SKILL.md` — do not edit by hand.\n",
       "**New** = authored in this repo from research kept in the Notion knowledge base; **Upstream** = ported from "
       "`samuelgursky/davinci-resolve-mcp` (see `UPSTREAM.md`).\n",
       "How the layers fit: the *guide* and *craft* skills know Resolve and editing; the *MCP* skills know how to drive it. "
       "Guide skills say what the scripting API cannot do and give the manual UI steps instead.\n"]
seen = set()
for title, names in GROUPS:
    out.append(f"\n## {title}\n\n| Skill | Origin | Use it for |\n|---|---|---|")
    for n in names:
        d = re.search(r"^description:\s*(.*)$", (ROOT / f"skills/{n}/SKILL.md").read_text(), re.M).group(1)
        first = re.split(r"(?<=[.])\s", d)[0][:220]
        out.append(f"| `{n}` | {'New' if n in NEW else 'Upstream'} | {first} |")
        seen.add(n)
missing = {p.name for p in (ROOT / "skills").iterdir()} - seen
assert not missing, f"skills missing from GROUPS: {missing}"
(ROOT / "docs/skill-library.md").write_text("\n".join(out) + "\n")
print(f"{len(seen)} skills indexed")
